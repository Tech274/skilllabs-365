/**
 * Single source of truth for the app's HTTP security headers.
 *
 * Consumed by:
 *   - `vite.config.ts` (dev + `vite preview` responses, and a build-time CSP
 *     <meta> injected into index.html so the policy survives hosts that ignore
 *     header files),
 *   - `scripts/generate-headers.ts`, which writes `public/_headers` for the
 *     static host (Netlify/Cloudflare `_headers` syntax).
 *
 * Scope note: these are document-level headers, so they cover every route —
 * student (`/student`, `/cloud-access/*`, `/lab/*`) and admin (`/admin/*`)
 * alike. Clickjacking and injection protection must not depend on which route
 * happens to be mounted.
 */

/** Remote origins the app legitimately talks to or embeds. */
const SUPABASE = ["https://*.supabase.co", "wss://*.supabase.co"];
const LOVABLE = ["https://*.lovable.app", "https://*.lovableproject.com"];

/** Google Fonts stylesheet + font files (Inter / JetBrains Mono branding). */
const GOOGLE_FONTS_CSS = ["https://fonts.googleapis.com"];
const GOOGLE_FONTS_FILES = ["https://fonts.gstatic.com"];

/**
 * Guacamole gateways (embedded in an iframe on the lab session page).
 * Dual-host: AWS Guac + Azure Guac — CSP allowlist only; routing unchanged.
 * Both origins MUST appear in connect-src AND frame-src. Live skillhub365.co.in
 * deploy e7cbd2a4 had guac only — guac-azure was missing until this fleet-trust fix.
 */
const GUACAMOLE = [
  "https://guac.skillhub365.co.in",
  "https://guac-azure.skillhub365.co.in",
];

/** Cloud consoles opened from a generated access link. */
const CLOUD_CONSOLES = [
  "https://portal.azure.com",
  "https://*.console.aws.amazon.com",
  "https://signin.aws.amazon.com",
  "https://console.cloud.google.com",
];

export interface HeaderOptions {
  /** `true` for dev/preview: relaxes CSP just enough for Vite HMR and the Lovable preview iframe. */
  dev?: boolean;
  /** Extra origins allowed in connect-src / frame-src (comma separated), e.g. a self-hosted gateway. */
  extraOrigins?: string;
}

function split(list?: string): string[] {
  return (list ?? "").split(",").map(s => s.trim()).filter(Boolean);
}

export function contentSecurityPolicy(opts: HeaderOptions = {}): string {
  const extra = split(opts.extraOrigins);
  const dev = Boolean(opts.dev);

  const connect = [
    "'self'",
    ...SUPABASE,
    ...GUACAMOLE,
    ...CLOUD_CONSOLES,
    ...GOOGLE_FONTS_CSS,
    ...GOOGLE_FONTS_FILES,
    ...extra,
    // Vite HMR + the dev overlay speak websocket to the local server.
    ...(dev ? ["ws:", "wss:", "http://localhost:*", "http://127.0.0.1:*", ...LOVABLE] : []),
  ];

  const frame = ["'self'", ...GUACAMOLE, ...CLOUD_CONSOLES, ...extra];

  // Who may embed *us*. Production: nobody. Dev: the Lovable preview iframe.
  const frameAncestors = dev ? ["'self'", ...LOVABLE, "http://localhost:*"] : ["'none'"];

  const directives: Record<string, string[]> = {
    "default-src": ["'self'"],
    // React/Vite inject inline bootstrap + style tags; 'unsafe-eval' is dev-only (HMR).
    "script-src": ["'self'", "'unsafe-inline'", ...(dev ? ["'unsafe-eval'"] : [])],
    "style-src": ["'self'", "'unsafe-inline'", ...GOOGLE_FONTS_CSS],
    "img-src": ["'self'", "data:", "blob:", "https:"],
    "font-src": ["'self'", "data:", ...GOOGLE_FONTS_FILES],
    "connect-src": connect,
    "frame-src": frame,
    "worker-src": ["'self'", "blob:"],
    "media-src": ["'self'", "blob:", "data:"],
    "object-src": ["'none'"],
    "base-uri": ["'self'"],
    "form-action": ["'self'"],
    "frame-ancestors": frameAncestors,
  };

  const policy = Object.entries(directives)
    .map(([k, v]) => `${k} ${v.join(" ")}`)
    .join("; ");

  return dev ? policy : `${policy}; upgrade-insecure-requests`;
}

export function securityHeaders(opts: HeaderOptions = {}): Record<string, string> {
  const headers: Record<string, string> = {
    "Content-Security-Policy": contentSecurityPolicy(opts),
    // Legacy clickjacking guard for agents that ignore frame-ancestors.
    "X-Frame-Options": opts.dev ? "SAMEORIGIN" : "DENY",
    "X-Content-Type-Options": "nosniff",
    "Referrer-Policy": "strict-origin-when-cross-origin",
    "Permissions-Policy": "camera=(), microphone=(), geolocation=(), payment=(), usb=(), interest-cohort=()",
    "Cross-Origin-Opener-Policy": "same-origin",
    "Cross-Origin-Resource-Policy": "same-site",
  };

  // HSTS only makes sense on the real HTTPS origin; sending it from a local
  // http dev server would pin localhost to https for the whole browser profile.
  if (!opts.dev) {
    headers["Strict-Transport-Security"] = "max-age=63072000; includeSubDomains; preload";
  }

  return headers;
}

/** Renders `public/_headers` (Netlify / Cloudflare Pages syntax). */
export function headersFile(opts: HeaderOptions = {}): string {
  const headers = securityHeaders(opts);
  const lines = [
    "# Generated by scripts/generate-headers.ts — do not edit by hand.",
    "# Applies to every route: student, admin and public pages.",
    "/*",
    ...Object.entries(headers).map(([k, v]) => `  ${k}: ${v}`),
    "",
    "# Static assets are content-hashed and safe to cache immutably.",
    "/assets/*",
    "  Cache-Control: public, max-age=31536000, immutable",
    "",
  ];
  return lines.join("\n");
}
